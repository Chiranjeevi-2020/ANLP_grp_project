"""Linguistic Naturalness and Lexical Diversity Audit for proto_1.

Audits whether post-switch utterances generated by frozen LM under controller instructions
preserve natural language characteristics (low perplexity, high lexical diversity,
fluent sentence lengths, and absence of degenerate repetition).
"""
import argparse
import collections
import re
from pathlib import Path

import numpy as np

from . import agents
from .config import load_config, load_spec, read_jsonl, run_dir, sub, write_json
from .tracker import ExperimentTracker

METHODS = ["no_switch", "scripted", "prompt_only", "untrained_controller", "rl_controller", "rl_controller_greedy"]


def tokenize_words(text):
    return re.findall(r"\b\w+\b", text.lower())


def distinct_ngrams(messages, n=1):
    """Calculates Distinct-n metric: unique n-grams divided by total n-grams."""
    total, unique = 0, set()
    for m in messages:
        words = tokenize_words(m)
        if len(words) < n:
            continue
        grams = [tuple(words[i:i + n]) for i in range(len(words) - n + 1)]
        total += len(grams)
        unique.update(grams)
    return round(float(len(unique) / max(1, total)), 4)


def repetition_ratio(messages):
    """Detects immediate word-repetition loops (e.g., 'we we we' or repeated phrases)."""
    repeated_counts = 0
    for m in messages:
        words = tokenize_words(m)
        has_repeat = any(words[i] == words[i + 1] for i in range(len(words) - 1))
        if has_repeat:
            repeated_counts += 1
    return round(float(repeated_counts / max(1, len(messages))), 4)


def run_linguistic_audit(cfg, spec, lm=None, tracker=None):
    tracker_created = False
    if tracker is None:
        tracker = ExperimentTracker(cfg, job_type="linguistic-audit")
        tracker_created = True

    print("\n=======================================================")
    print("  Running Linguistic Naturalness & Diversity Audit")
    print("=======================================================\n", flush=True)

    if lm is None:
        from .lm import FrozenLM
        lm = FrozenLM(cfg["model_name"], cfg.get("device", "auto"), cfg.get("dtype", None))

    metrics_by_method = {}
    pub_test = read_jsonl(sub(cfg, "data", "test_public.jsonl"))
    hist_by_id = {r["example_id"]: r["history"] for r in pub_test}

    for method in METHODS:
        pub_path = sub(cfg, "rollouts", "test", f"{method}.public.jsonl")
        if not pub_path.exists():
            print(f"[linguistic_audit] Skipping {method} (no rollouts found at {pub_path})")
            continue

        rows = read_jsonl(pub_path)
        messages = [r["message"] for r in rows]
        word_lens = [len(tokenize_words(m)) for m in messages]
        char_lens = [len(m) for m in messages]

        # Calculate perplexity under frozen LM given conversation context
        context_prompts = [lm.chat(agents.SYSTEM_A, f"Conversation so far:\n{agents.render_history(hist_by_id[r['example_id']])}\n\n[C joins the conversation]\nA: ")
                           for r in rows]
        ppl_res = lm.compute_loss_and_perplexity(context_prompts, messages, batch_size=cfg["gen"]["batch_size"])

        d1 = distinct_ngrams(messages, n=1)
        d2 = distinct_ngrams(messages, n=2)
        rep = repetition_ratio(messages)

        method_stats = {
            "method": method,
            "n_messages": len(messages),
            "mean_word_length": round(float(np.mean(word_lens)), 2),
            "std_word_length": round(float(np.std(word_lens)), 2),
            "mean_char_length": round(float(np.mean(char_lens)), 2),
            "distinct_1": d1,
            "distinct_2": d2,
            "immediate_repetition_rate": rep,
            "lm_loss": round(ppl_res["loss"], 4),
            "perplexity": round(ppl_res["perplexity"], 2),
        }
        metrics_by_method[method] = method_stats

        print(f"[{method:22s}] PPL={method_stats['perplexity']:6.2f} | D-1={d1:.3f} | D-2={d2:.3f} "
              f"| Words={method_stats['mean_word_length']:.1f} | Rep={rep:.2f}")

        tracker.log({
            f"linguistic/{method}/perplexity": method_stats["perplexity"],
            f"linguistic/{method}/distinct_1": d1,
            f"linguistic/{method}/distinct_2": d2,
            f"linguistic/{method}/mean_words": method_stats["mean_word_length"],
            f"linguistic/{method}/repetition_rate": rep,
        })

    # Save JSON report
    out_dir = sub(cfg, "audit")
    out_dir.mkdir(parents=True, exist_ok=True)
    json_path = out_dir / "linguistic_audit.json"
    write_json(json_path, metrics_by_method)

    # Save Markdown report
    md_lines = [
        f"# Linguistic Naturalness & Diversity Audit (`{cfg['run_name']}`)",
        "",
        "Evaluates the surface naturalness and lexical richness of post-switch dialogue generated under each method.",
        "",
        "| Method | Perplexity (PPL $\\downarrow$) | LM Cross-Entropy | Distinct-1 ($\\uparrow$) | Distinct-2 ($\\uparrow$) | Mean Words | Repetition Rate |",
        "|---|---|---|---|---|---|---|",
    ]
    for method, s in metrics_by_method.items():
        md_lines.append(
            f"| `{method}` | **{s['perplexity']:.2f}** | {s['lm_loss']:.3f} | {s['distinct_1']:.3f} | {s['distinct_2']:.3f} | {s['mean_word_length']:.1f} | {s['immediate_repetition_rate']:.3f} |"
        )
    md_lines += [
        "",
        "### Interpretation:",
        "- **Perplexity (PPL):** Lower perplexity under the frozen base model indicates that generated utterances follow standard natural English probability distributions, confirming that the controller has not induced cryptographic token noise or language drift.",
        "- **Distinct-1 & Distinct-2:** Higher ratios demonstrate high vocabulary richness and absence of robotic mode collapse.",
        "- **Repetition Rate:** Fraction of messages displaying consecutive word duplicates.",
    ]
    md_path = out_dir / "LINGUISTIC_AUDIT.md"
    with open(md_path, "w") as f:
        f.write("\n".join(md_lines) + "\n")

    if tracker_created:
        tracker.finish()

    print(f"\n[linguistic_audit] Audit saved to {md_path} and {json_path}")
    return metrics_by_method


def main():
    parser = argparse.ArgumentParser(description="Linguistic Naturalness and Diversity Audit.")
    parser.add_argument("--config", default="proto_1/configs/tiny.json", help="Path to config JSON")
    args = parser.parse_args()

    cfg = load_config(args.config)
    spec = load_spec()
    run_linguistic_audit(cfg, spec)


if __name__ == "__main__":
    main()
